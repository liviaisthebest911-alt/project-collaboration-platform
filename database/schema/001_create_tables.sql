-- Project collaboration platform - PostgreSQL 16
-- Step 1: base tables, row constraints and indexes.
-- Run once in an EMPTY project_collab database using Execute SQL Script.
-- Cross-table business rules and transactional workflows are a later step.
-- No existing tables or data are deleted by this script.

BEGIN;
SET LOCAL search_path = public;

DO $$
BEGIN
    IF current_database() <> 'project_collab' THEN
        RAISE EXCEPTION 'Connect to project_collab before running this script.';
    END IF;
END;
$$;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    bio TEXT,
    profile_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE domain (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uq_domain_name UNIQUE (name)
);

CREATE TABLE skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE skill_domain (
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    domain_id BIGINT NOT NULL REFERENCES domain(id),
    PRIMARY KEY (skill_id, domain_id)
);

CREATE TABLE user_skill (
    user_id BIGINT NOT NULL REFERENCES users(id),
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    level SMALLINT NOT NULL,
    PRIMARY KEY (user_id, skill_id),
    CONSTRAINT ck_user_skill_level CHECK (level BETWEEN 1 AND 5)
);

CREATE TABLE project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'planning',
    repository_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_activity_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_project_status CHECK (
        status IN ('planning', 'active', 'paused', 'completed', 'cancelled')
    )
);

CREATE TABLE project_domain (
    project_id BIGINT NOT NULL REFERENCES project(id),
    domain_id BIGINT NOT NULL REFERENCES domain(id),
    PRIMARY KEY (project_id, domain_id)
);

CREATE TABLE position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id),
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    slots INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'open',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    CONSTRAINT ck_position_slots CHECK (slots > 0),
    CONSTRAINT ck_position_status CHECK (status IN ('open', 'closed')),
    CONSTRAINT ck_position_closed_at CHECK (
        (status = 'open' AND closed_at IS NULL)
        OR (status = 'closed' AND closed_at IS NOT NULL AND closed_at >= created_at)
    )
);

CREATE TABLE position_skill_requirement (
    position_id BIGINT NOT NULL REFERENCES position(id),
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    min_level SMALLINT NOT NULL,
    PRIMARY KEY (position_id, skill_id),
    CONSTRAINT ck_position_skill_min_level CHECK (min_level BETWEEN 1 AND 5)
);

CREATE TABLE project_member (
    project_id BIGINT NOT NULL REFERENCES project(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    role VARCHAR(20) NOT NULL DEFAULT 'member',
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMPTZ,
    PRIMARY KEY (project_id, user_id),
    CONSTRAINT ck_project_member_role CHECK (role IN ('owner', 'member')),
    CONSTRAINT ck_project_member_dates CHECK (left_at IS NULL OR left_at >= joined_at)
);

CREATE TABLE position_assignment (
    user_id BIGINT NOT NULL REFERENCES users(id),
    position_id BIGINT NOT NULL REFERENCES position(id),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, position_id),
    CONSTRAINT ck_position_assignment_dates CHECK (
        ended_at IS NULL OR ended_at >= started_at
    )
);

CREATE TABLE application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position_id BIGINT NOT NULL REFERENCES position(id),
    applicant_id BIGINT NOT NULL REFERENCES users(id),
    processed_by BIGINT REFERENCES users(id),
    message TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at TIMESTAMPTZ,
    CONSTRAINT ck_application_status CHECK (
        status IN ('pending', 'accepted', 'rejected', 'withdrawn')
    ),
    CONSTRAINT ck_application_decision CHECK (
        (status IN ('pending', 'withdrawn')
            AND processed_by IS NULL AND decided_at IS NULL)
        OR (status IN ('accepted', 'rejected')
            AND processed_by IS NOT NULL AND decided_at IS NOT NULL
            AND decided_at >= applied_at)
    )
);

CREATE TABLE task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id),
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'todo',
    due_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    CONSTRAINT ck_task_status CHECK (status IN ('todo', 'in_progress', 'done')),
    CONSTRAINT ck_task_updated_at CHECK (updated_at >= created_at),
    CONSTRAINT ck_task_completed_at CHECK (
        (status IN ('todo', 'in_progress') AND completed_at IS NULL)
        OR (status = 'done' AND completed_at IS NOT NULL AND completed_at >= created_at)
    )
);

CREATE TABLE task_assignment (
    task_id BIGINT NOT NULL REFERENCES task(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unassigned_at TIMESTAMPTZ,
    PRIMARY KEY (task_id, user_id),
    CONSTRAINT ck_task_assignment_dates CHECK (
        unassigned_at IS NULL OR unassigned_at >= assigned_at
    )
);

CREATE TABLE project_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id),
    changed_by BIGINT NOT NULL REFERENCES users(id),
    old_status VARCHAR(20) NOT NULL,
    new_status VARCHAR(20) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note TEXT,
    CONSTRAINT ck_history_old_status CHECK (
        old_status IN ('planning', 'active', 'paused', 'completed', 'cancelled')
    ),
    CONSTRAINT ck_history_new_status CHECK (
        new_status IN ('planning', 'active', 'paused', 'completed', 'cancelled')
    ),
    CONSTRAINT ck_history_status_change CHECK (old_status <> new_status)
);

CREATE TABLE project_handover (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id),
    from_user_id BIGINT NOT NULL REFERENCES users(id),
    to_user_id BIGINT NOT NULL REFERENCES users(id),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    note TEXT,
    decided_at TIMESTAMPTZ,
    CONSTRAINT ck_handover_users CHECK (from_user_id <> to_user_id),
    CONSTRAINT ck_handover_status CHECK (
        status IN ('pending', 'accepted', 'rejected', 'cancelled')
    ),
    CONSTRAINT ck_handover_decision CHECK (
        (status IN ('pending', 'cancelled') AND decided_at IS NULL)
        OR (status IN ('accepted', 'rejected')
            AND decided_at IS NOT NULL AND decided_at >= requested_at)
    )
);

-- These partial indexes enforce AT MOST one matching row, not AT LEAST one.
CREATE UNIQUE INDEX uq_project_active_owner
    ON project_member (project_id)
    WHERE role = 'owner' AND left_at IS NULL;

CREATE UNIQUE INDEX uq_application_pending
    ON application (position_id, applicant_id)
    WHERE status = 'pending';

CREATE UNIQUE INDEX uq_handover_pending
    ON project_handover (project_id)
    WHERE status = 'pending';

-- Indexes for common foreign-key joins not covered by a leading PK column.
CREATE INDEX ix_skill_domain_domain ON skill_domain (domain_id);
CREATE INDEX ix_user_skill_skill ON user_skill (skill_id);
CREATE INDEX ix_project_creator ON project (creator_id);
CREATE INDEX ix_project_domain_domain ON project_domain (domain_id);
CREATE INDEX ix_position_project ON position (project_id);
CREATE INDEX ix_position_skill_skill ON position_skill_requirement (skill_id);
CREATE INDEX ix_member_user ON project_member (user_id);
CREATE INDEX ix_position_assignment_position ON position_assignment (position_id);
CREATE INDEX ix_application_position ON application (position_id);
CREATE INDEX ix_application_applicant ON application (applicant_id);
CREATE INDEX ix_application_processor ON application (processed_by);
CREATE INDEX ix_task_project ON task (project_id);
CREATE INDEX ix_task_assignment_user ON task_assignment (user_id);
CREATE INDEX ix_history_project_time ON project_status_history (project_id, changed_at);
CREATE INDEX ix_history_changed_by ON project_status_history (changed_by);
CREATE INDEX ix_handover_project ON project_handover (project_id);
CREATE INDEX ix_handover_from_user ON project_handover (from_user_id);
CREATE INDEX ix_handover_to_user ON project_handover (to_user_id);

COMMIT;

